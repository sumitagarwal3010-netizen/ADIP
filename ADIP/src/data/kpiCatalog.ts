/**
 * ADIP KPI Governance Catalog
 * ----------------------------------------------------------
 * Single source of truth for every KPI surfaced anywhere in the platform.
 * Each entry documents: definition, formula, source, frequency, owner,
 * the executive consumer of the metric, and the question it answers.
 *
 * The /kpi-catalog route renders this catalog and exposes a Generate
 * action that produces a downloadable KPI dictionary (CSV/MD) which
 * lands in the Universal Artifacts Repository.
 */

export type KpiAnswers =
  | 'Health'
  | 'Risk'
  | 'Progress'
  | 'Adoption'
  | 'Compliance'
  | 'Value';

export interface KpiCatalogEntry {
  id: string;
  /** Human-readable KPI name as shown on the dashboard. */
  name: string;
  /** Center / page where the KPI is surfaced. */
  center: string;
  /** Concise definition. */
  definition: string;
  /** Calculation formula in plain English. */
  formula: string;
  /** Origin system / dataset / engine that feeds the value. */
  source: string;
  /** Refresh cadence. */
  frequency: 'Real-time' | '30s' | 'Hourly' | 'Daily' | 'Weekly' | 'Monthly' | 'Per build';
  /** Accountable role that owns the data quality of this KPI. */
  owner: string;
  /** Executive role consuming the KPI for decision-making. */
  executiveConsumer: 'CIO' | 'CTO' | 'CISO' | 'CRO' | 'COO' | 'CFO' | 'CDO' | 'CEO' | 'Board';
  /** Which executive question the KPI answers. */
  answers: KpiAnswers;
  /** Optional unit suffix (%, /100, count, ₹, ms, etc). */
  unit?: string;
  /** Optional acceptable threshold/target. */
  target?: string;
}

