export interface KpiCatalogStats {
  totalKpis: number;
  uniqueCenters: number;
  byAnswer: Record<KpiAnswers, number>;
  byConsumer: Record<KpiCatalogEntry['executiveConsumer'], number>;
}

export function computeKpiCatalogStats(): KpiCatalogStats {
  const byAnswer = { Health: 0, Risk: 0, Progress: 0, Adoption: 0, Compliance: 0, Value: 0 } as Record<KpiAnswers, number>;
  const byConsumer = {
    CIO: 0, CTO: 0, CISO: 0, CRO: 0, COO: 0, CFO: 0, CDO: 0, CEO: 0, Board: 0,
  } as Record<KpiCatalogEntry['executiveConsumer'], number>;
  const centers = new Set<string>();
  KPI_CATALOG.forEach((k) => {
    byAnswer[k.answers] += 1;
    byConsumer[k.executiveConsumer] += 1;
    centers.add(k.center);
  });
  return {
    totalKpis: KPI_CATALOG.length,
    uniqueCenters: centers.size,
    byAnswer,
    byConsumer,
  };
}
